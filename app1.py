# recebe o nome do usário na vriavél
name = input("Qual o seu nome?")

# receba a idade do usuário na variável
age = input("Qual a sua idade?")  

# Exibe uma mensagem formatada
print()
print("Olá", name, "!")
print("Você tem", age, "anos")

# Usando esting formatada (f) - melhor prática
print()
print(f"Olá {name}! Você tem {age} anos.")
